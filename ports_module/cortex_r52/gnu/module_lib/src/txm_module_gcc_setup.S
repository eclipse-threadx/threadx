    .syntax unified
    .arm
    .text
    .align  2

    .global _gcc_setup
    .type   _gcc_setup, %function

@ Supplied by the module's linker script.  The two segment origins are nominal
@ addresses the module never runs at -- see link_demo_module.lds.

    .extern __code_segment_start__
    .extern __data_segment_start__
    .extern __got_load_start__
    .extern __new_got_start__
    .extern __new_got_end__
    .extern __data_load_start__
    .extern __data_start__
    .extern __data_end__
    .extern __bss_start__
    .extern __bss_end__

_gcc_setup:

    PUSH    {r4-r7, lr}

@   The two deltas every address below is corrected by.  Everything the linker
@   emitted is expressed against the nominal origins; everything that exists at
@   run time is at the same offset from the real base.

    LDR     r3, =__code_segment_start__
    SUB     r4, r0, r3                      @ r4 = code delta, real - nominal
    LDR     r3, =__data_segment_start__
    SUB     r5, r9, r3                      @ r5 = data delta, real - nominal

@   ---------------------------------------------------------------------------
@   1.  The global offset table.
@   ---------------------------------------------------------------------------
@
@   Read from the image, written to the module's data area, one entry at a time,
@   with each entry rebased according to which segment it points into.  The test
@   is a single unsigned compare against the nominal data origin, which is what
@   the linker script's far-apart origins exist to make sound: everything below
@   it is code or read-only data and moves with the code, everything at or above
@   it is writable data and moves with the data area.
@
@   A zero entry is left alone.  The linker leaves an entry zero when it had
@   nothing to put there, and rebasing it would turn a recognisable null into a
@   plausible-looking pointer into the middle of the module.

    LDR     r1, =__got_load_start__
    ADD     r1, r1, r4                      @ Source, in the image
    LDR     r2, =__new_got_start__
    ADD     r2, r2, r5                      @ Destination, in the data area
    LDR     r3, =__new_got_end__
    ADD     r3, r3, r5                      @ One past the last entry
    LDR     r7, =__data_segment_start__     @ The code / data dividing line

got_loop:
    CMP     r2, r3
    BHS     got_done
    LDR     r6, [r1], #4                    @ Pickup the entry as linked
    CMP     r6, #0
    BEQ     got_store                       @ Never filled in; leave it alone
    CMP     r6, r7
    ADDLO   r6, r6, r4                      @ Below the line: a code address
    ADDHS   r6, r6, r5                      @ At or above: a data address
got_store:
    STR     r6, [r2], #4
    B       got_loop
got_done:

@   ---------------------------------------------------------------------------
@   2.  Initialised data.
@   ---------------------------------------------------------------------------
@
@   Byte at a time.  The run-time destination is the manager's data base plus a
@   linker offset, and while both happen to be word aligned today, a byte copy
@   does not have to care -- and this runs once per module start, where the cost
@   of not having to think about it is nothing.

    LDR     r1, =__data_load_start__
    ADD     r1, r1, r4                      @ Source, in the image
    LDR     r2, =__data_start__
    ADD     r2, r2, r5                      @ Destination, in the data area
    LDR     r3, =__data_end__
    ADD     r3, r3, r5

data_loop:
    CMP     r2, r3
    BHS     data_done
    LDRB    r6, [r1], #1
    STRB    r6, [r2], #1
    B       data_loop
data_done:

@   ---------------------------------------------------------------------------
@   3.  Zero-initialised data.
@   ---------------------------------------------------------------------------
@
@   The manager has already zeroed the whole allocation, so this is redundant
@   with the loader this port ships.  It is here because that is the loader's
@   behaviour and not the module's contract: a module that only works because
@   its loader happens to memset is a module that breaks on the next loader.

    LDR     r1, =__bss_start__
    ADD     r1, r1, r5
    LDR     r2, =__bss_end__
    ADD     r2, r2, r5
    MOV     r6, #0

bss_loop:
    CMP     r1, r2
    BHS     bss_done
    STRB    r6, [r1], #1
    B       bss_loop
bss_done:

@   The module's data is now readable and writable through r9, and the module
@   proper can run.  A data barrier because the GOT and .data were just written
@   as data and are about to be read as the module's working set; no instruction
@   barrier, because nothing executable was modified.

    DSB
    POP     {r4-r7, lr}
    BX      lr

    .size   _gcc_setup, . - _gcc_setup
